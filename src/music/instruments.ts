export const searchInstruments = (query: string) => {
  const words = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  return INSTRUMENTS.filter((entry) => words.every((word) => `${entry.name} ${entry.family}`.toLowerCase().includes(word)));
};
